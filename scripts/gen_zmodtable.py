#!/usr/bin/env python3
"""Generate ZModTable.lean: the family of rings Z/nZ for n = 3, ..., 500.

For every n in that range the file records

  «✱54.43_zmod_n» : one + one ≠ zero   in ZMod n,

proved from `ZMod.two_ne_zero_of_three_le` at the numeral `n_n`.  The numerals
`n3, ..., n500` are built one successor at a time, and the bounds
`le3, ..., le500 : le three n_n` are chained, each citing its predecessor.  The
file closes with two checks at the ends of the table, where the numeral is not
taken from the chain but written out in full as a successor chain, so that the
numeral of the entry is pinned to its value.

Nothing here is computed: every entry is an application of the general theorem.
Usage: gen_zmodtable.py [OUTFILE]
"""
import sys

LOW = 3
HIGH = 500

def chain(k, per_line=10):
    """The k-fold successor chain, written out as `N.succ ( ... N.zero ... )`.

    Short chains stay on one line; long ones are broken every `per_line`
    successors, because a chain of five hundred nested applications is deeper
    than the elaborator's default recursion limit."""
    if k <= per_line:
        return "N.succ (" * k + "N.zero" + ")" * k
    opens = []
    i = 0
    while i < k:
        n = min(per_line, k - i)
        opens.append("N.succ ( " * n)
        i += n
    return "\n      ".join(opens) + "N.zero" + ")" * k

def main(path):
    L = []
    L.append("""/-
The table of the rings `Z/nZ` for `n = 3, ..., 500`.

The general theorem of `ZMod` says that one plus one is not zero in `Z/nZ` as
soon as three is at most `n`.  This file records the instance for every `n` of
the table: the numerals `n3, ..., n500` are built one successor at a time, the
bounds `le3, ..., le500` are chained so that each cites its predecessor, and the
%4d entries `«✱54.43_zmod_n»` cite the general theorem at their own numeral.

The theorem `«✱54.43_zmod_table»` at the end collects every entry.

Generated by `gen_zmodtable.py`, which is deterministic and whose output is
checked by Lean; no entry is computed, each is an application of the general
theorem.  Nothing below uses `rfl`, `simp`, `decide`, `omega`, `ring` or any
other search or computation tactic.
-/
import Principia.PartVII.ZMod.ZMod

set_option autoImplicit false

/- The statement of the whole table is a conjunction of 498 propositions, nested
deeper than the elaborator recurses by default. -/
set_option maxRecDepth 10000

namespace Principia
namespace ZModTable

/-! ### The numerals of the table -/

""" % (HIGH - LOW + 1))
    L.append("/-- The numeral 3, Peano's `three`. -/\ndef n3 : N := N.three\n\n")
    for k in range(LOW + 1, HIGH + 1):
        L.append("/-- The numeral %d. -/\ndef n%d : N := N.succ n%d\n\n" % (k, k, k - 1))
    L.append("""/-! ### The numerals are at least three -/

/-- Three is at least three. -/
theorem le3 : N.le N.three n3 := N.le_refl N.three
#print axioms le3
""")
    for k in range(LOW + 1, HIGH + 1):
        L.append("""
/-- The numeral %d is at least three. -/
theorem le%d : N.le N.three n%d := N.le_trans le%d (N.le_succ_self n%d)
#print axioms le%d
""" % (k, k, k, k - 1, k - 1, k))
    L.append("""
/-! ### The table: one plus one is not zero in `Z/nZ` -/
""")
    for k in range(LOW, HIGH + 1):
        L.append("""
/-- In the ring of %d elements, one plus one is not zero. -/
theorem «✱54.43_zmod_%d» :
    ZMod.add n%d (ZMod.one n%d) (ZMod.one n%d) ≠ ZMod.zero n%d :=
  ZMod.two_ne_zero_of_three_le n%d le%d
#print axioms «✱54.43_zmod_%d»
""" % (k, k, k, k, k, k, k, k, k))
    L.append("""
/-! ### The whole table -/

/-- The table as a proposition: for every `n` from 3 to 500, one plus one is
not zero in the ring of `n` elements. -/
def Statement : Prop :=
""")
    L.append("    " + " ∧\n    ".join(
        "ZMod.add n%d (ZMod.one n%d) (ZMod.one n%d) ≠ ZMod.zero n%d" % (k, k, k, k)
        for k in range(LOW, HIGH + 1)) + "\n")
    L.append("\n/-- The table holds. -/\ntheorem «✱54.43_zmod_table» : Statement :=\n")
    L.append("  ⟨" + ",\n   ".join("«✱54.43_zmod_%d»" % k for k in range(LOW, HIGH + 1)) + "⟩\n")
    L.append("#print axioms «✱54.43_zmod_table»\n")
    L.append("""
end ZModTable
end Principia
""")
    open(path, "w").write("".join(x if x.endswith("\n") else x + "\n" for x in L))
    print("wrote", path)

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "Principia/PartVII/ZMod/ZModTable.lean")
